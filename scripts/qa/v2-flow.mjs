// Blueprint v2 walkthrough: onboarding steps, home, search, My Series, reader end. QA only.
import { chromium } from "playwright";
const base = process.env.BASE || "http://localhost:4173";
const OUT = process.env.OUT || "/tmp/v2";
const theme = process.env.THEME || "dark";
const W = Number(process.env.W || 390), H = Number(process.env.H || 844);
const mobile = W < 1024;
const browser = await chromium.launch();
const ctx = await browser.newContext({ serviceWorkers: "block", colorScheme: theme, viewport: { width: W, height: H }, isMobile: mobile, hasTouch: mobile });
await ctx.route((u) => u.hostname.endsWith("mangadex.org") || u.hostname.endsWith("mangadex.network"), async (route) => { try { const r = await fetch(route.request().url()); await route.fulfill({ status: r.status, contentType: r.headers.get("content-type") ?? "image/jpeg", body: Buffer.from(await r.arrayBuffer()) }); } catch { await route.abort(); } });
await ctx.addInitScript(`localStorage.setItem("dawghwa:settings", JSON.stringify({ theme: "${theme}" }))`);
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push("pageerror " + e.message));
page.on("console", (m) => m.type() === "error" && errs.push("console " + m.text()));
const tag = `${theme}-${W}`;
const shot = async (n, full = false) => { await page.screenshot({ path: `${OUT}/${tag}-${n}.png`, fullPage: full }); console.log(n); };
await page.goto(base + "/welcome");
await page.waitForTimeout(3500);
await shot("ob1");
await page.getByRole("button", { name: "Fantasy" }).click();
await page.getByRole("button", { name: "Romance" }).click();
await page.waitForTimeout(300);
await shot("ob1b");
await page.getByRole("button", { name: "Continue" }).click();
await page.getByRole("button", { name: /Manhwa/ }).click();
await shot("ob2");
await page.getByRole("button", { name: "Continue" }).click();
await shot("ob3");
await page.getByRole("button", { name: "Continue" }).click();
await page.waitForTimeout(400);
await shot("ob4");
await page.getByRole("button", { name: "Save" }).click();
await page.waitForURL(base + "/");
await page.waitForTimeout(5000);
await shot("home");
await page.mouse.wheel(0, 900);
await page.waitForTimeout(2500);
await shot("home2");
await page.goto(base + "/search");
await page.waitForTimeout(4000);
await shot("search");
// read a chapter so My Series has a row
await page.goto(base + "/read/mangadex/9a414441-bbad-43f1-a3a7-dc262ca790a3/d3c06606-4ee7-4454-a3a7-ffdb9ecf5d26");
await page.waitForTimeout(6000);
for (let i = 0; i < 40; i++) { await page.keyboard.press("End"); await page.waitForTimeout(250); }
await page.waitForTimeout(2500);
await shot("reader-end");
await page.goto(base + "/title/mangadex/77bee52c-d2d6-44ad-a33a-1734c1fe696a");
await page.waitForTimeout(3000);
const save = page.getByRole("button", { name: /^Save/ }).first();
if (await save.count()) { await save.click().catch(() => {}); await page.waitForTimeout(500); const pick = page.getByRole("menuitemradio", { name: /Reading/ }).first(); if (await pick.count()) await pick.click().catch(() => {}); }
await page.goto(base + "/library?tab=recent");
await page.waitForTimeout(3000);
await shot("library");
await page.goto(base + "/library");
await page.waitForTimeout(2000);
await shot("library-saved");
console.log(errs.slice(0, 12).join("\n"));
await browser.close();
