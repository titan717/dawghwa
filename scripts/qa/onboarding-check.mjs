import { chromium } from "playwright";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errs=[]; p.on("console", m => m.type()==="error" && errs.push(m.text()));
await p.goto("http://localhost:4173/"); await p.waitForURL(/welcome/);
const next = p.getByRole("button", { name: /^Continue/ });
console.log("disabled at 0:", await next.isDisabled());
await p.getByRole("button", { name: "Fantasy" }).click(); await p.getByRole("button", { name: "Romance" }).click();
console.log("label:", await next.innerText());
await p.screenshot({ path: "/tmp/shots/onb-2.png" });
await next.click(); console.log("step2 h1:", await p.locator("h1").innerText());
await p.getByRole("button", { name: /Manhwa/ }).click();
await p.getByRole("button", { name: /^Continue/ }).click(); console.log("step3 h1:", await p.locator("h1").innerText());
await p.getByRole("button", { name: /^Continue/ }).click();
await p.getByRole("button", { name: /^Save/ }).click();
await p.waitForTimeout(300); console.log("splash:", await p.getByRole("status").innerText()); await p.screenshot({ path: "/tmp/shots/onb-splash.png" });
await p.waitForURL(/\/$/, { timeout: 5000 }); console.log("home url ok");
await p.goto("http://localhost:4173/welcome?edit=1"); console.log("edit pressed Fantasy:", await p.getByRole("button", { name: "Fantasy" }).getAttribute("aria-pressed"));
console.log("errors", errs); await b.close();
